import OpenAI from "openai";

const openRouterClient = new OpenAI({
  baseURL: "https://openrouter.ai/api/v1",
  apiKey: process.env.OPENROUTER_API_KEY,
});

export async function generateAndUploadImage(prompt: string): Promise<string> {
  try {
    console.log("Generating image with OpenRouter SeeD model...");

    // Generate image using OpenRouter's SeeD model
    const apiResponse = await openRouterClient.chat.completions.create({
      model: "bytedance-seed/seedream-4.5",
      messages: [
        {
          role: "user",
          content: prompt,
        },
      ],
      // @ts-ignore - OpenRouter supports modalities but TypeScript doesn't know about it
      modalities: ["image", "text"],
    });

    const response = apiResponse.choices[0].message;

    // @ts-ignore - Access images property
    if (!response.images || response.images.length === 0) {
      throw new Error("No image generated by SeeD model");
    }

    // @ts-ignore - Access image URL
    const imageDataUrl = response.images[0].image_url.url; // Base64 data URL

    console.log("Image generated successfully, returning base64 data URL");

    // Return the base64 data URL directly (stored in database)
    // No need for external image hosting since we store the data URL
    return imageDataUrl;
  } catch (error) {
    console.error("Error generating/uploading image:", error);
    throw new Error("Failed to generate meal image");
  }
}
